const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');

let focused;
class Element {
  constructor() { this.children = []; this.handlers = {}; }
  addEventListener(type, handler) { this.handlers[type] = handler; }
  append(...children) {
    for (const child of children) if (typeof child === 'object') child.parent = this;
    this.children.push(...children);
  }
  replaceChildren(...children) { this.children = children; }
  focus() { focused = this; }
  select() {}
  setAttribute() {}
  removeAttribute(attribute) { delete this[attribute]; }
  remove() { this.parent.children = this.parent.children.filter(child => child !== this); }
}
const html = fs.readFileSync(require('node:path').join(__dirname, 'index.html'), 'utf8');
const elements = new Map(Array.from(html.matchAll(/id="([^"]+)"/g), ([_, id]) => [id, new Element()]));
const el = id => elements.get(id);
vm.runInNewContext(html.split('<script>')[1].split('</script>')[0], {
  document: {getElementById: el, createElement: () => new Element()},
});
const submit = () => el('form').handlers.submit({preventDefault() {}});
el('matched').onclick();
submit();
assert.match(el('feedback').children[0].textContent, /Title matched/);
assert.equal(el('source').href, 'https://doi.org/10.1145/3290605.3300233');
el('keep').onclick();
el('keep').onclick();
assert.equal(el('list').children.length, 1);
submit();
assert.equal(el('keep').disabled, true);
el('list').children[0].children[1].onclick();
assert.equal(el('list').children.length, 0);
assert.equal(el('keep').disabled, false);
el('missed').onclick();
submit();
assert.match(el('feedback').children[0].textContent, /No match/);
assert.equal(el('source').hidden, true);
assert.equal(el('keep').hidden, true);
el('edit').onclick();
assert.equal(focused, el('title'));
el('title').value = '  FABRICATION AND ERRORS IN THE BIBLIOGRAPHIC CITATIONS GENERATED BY CHATGPT ';
el('title').handlers.input();
assert.equal(el('result').hidden, true);
submit();
assert.equal(el('source').href, 'https://doi.org/10.1038/s41598-023-41032-5');
el('title').value = 'On human predictions with explanations and predictions of machine learning models: A case study on deception detection';
el('title').handlers.input();
submit();
assert.match(el('feedback').children[0].textContent, /No match/);
assert.match(el('feedback').children[1].textContent, /An unmatched title may still be real/);
assert.equal(el('source').hidden, true);
assert.equal(el('keep').hidden, true);
el('title').value = '  ';
submit();
assert.match(el('feedback').children[0].textContent, /Enter a paper title/);
console.log('PASS: match, DOI targets, save, deduplication, removal, fabricated and real out-of-catalogue misses, correction, stale result and blank input.');
